#!/usr/bin/env python3
# SwanStationUWP - turns the shaders the Vulkan renderer embedded (src/platform/vk/shaders_*.h: SPIR-V of the game's shaders
# and of the multi-pass presets) into Direct3D 11 bytecode: SPIRV-Cross writes HLSL (shader model 5.0), fxc compiles it, and
# each header is written again in src/platform/uwp with the same names, the arrays now holding DXBC.
#
#   SPIRV_CROSS=/path/to/spirv-cross python3 tools/make-d3d-chains.py
#
# The HLSL's resources keep the Vulkan layout: the uniform block (binding 0) is b0, the push constants are b1, the
# samplers are t<binding>/s<binding>. The vertex shaders' Y is flipped (Vulkan's clip space points down).
# Committed output, so builds don't need the tools. SPDX-License-Identifier: GPL-3.0-or-later
import concurrent.futures
import hashlib
import os
import re
import shutil
import struct
import subprocess
import sys
import glob

root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
src_dir = os.path.join(root, "src", "platform", "vk")
out_dir = os.path.join(root, "src", "platform", "uwp")
cache = os.path.join(os.environ.get("TEMP", "/tmp"), "ss-d3d-cache")
os.makedirs(cache, exist_ok=True)

spirv_cross = os.environ.get("SPIRV_CROSS") or shutil.which("spirv-cross")
if not spirv_cross:
    sys.exit("spirv-cross not found (set SPIRV_CROSS)")
fxc = os.environ.get("FXC") or shutil.which("fxc")
if not fxc:
    found = sorted(glob.glob(os.path.join(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)"),
                                          "Windows Kits", "10", "bin", "*", "x64", "fxc.exe")))
    if not found:
        sys.exit("fxc not found")
    fxc = found[-1]

HEADERS = [("shaders_royale.h", "shaders_royale.h"), ("shaders_ntsc.h", "shaders_ntsc.h"),
           ("shaders_crt.h", "shaders_crt.h"), ("shaders_spv.h", "shaders_game.h")]
ARRAY = re.compile(r"static const uint32_t (\w+)\[\] = \{(.*?)\};", re.S)


def compile_shader(name, words):
    vertex = name.endswith("_VERT")
    blob = struct.pack("<%dI" % len(words), *words)
    key = hashlib.sha1(blob + (b"v" if vertex else b"f") + b"2").hexdigest()
    cso = os.path.join(cache, key + ".cso")
    if os.path.exists(cso):
        return open(cso, "rb").read()
    spv = os.path.join(cache, key + ".spv")
    hlsl = os.path.join(cache, key + ".hlsl")
    open(spv, "wb").write(blob)
    args = [spirv_cross, spv, "--hlsl", "--shader-model", "50", "--output", hlsl]
    if vertex:
        args.append("--flip-vert-y")
    r = subprocess.run(args, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError("spirv-cross failed for %s: %s" % (name, r.stderr))
    text = open(hlsl).read()
    # the push constants: the block without a register goes to b1
    text = re.sub(r"cbuffer (\w+)\s*\n\{", r"cbuffer \1 : register(b1)\n{", text)
    open(hlsl, "w").write(text)
    last = None
    for opt in ("/O1", "/Od"):
        r = subprocess.run([fxc, "/nologo", opt, "/T", "vs_5_0" if vertex else "ps_5_0", "/E", "main", "/Fo", cso, hlsl],
                           capture_output=True, text=True)
        if r.returncode == 0 and os.path.exists(cso):
            return open(cso, "rb").read()
        last = r.stdout + r.stderr
    raise RuntimeError("fxc failed for %s (%s):\n%s" % (name, hlsl, last[:3000]))


def c_bytes(name, data):
    lines = ["static const uint8_t %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 24]) + ",")
    lines.append("};")
    return "\n".join(lines)


def convert(header, out_name):
    text = open(os.path.join(src_dir, header), encoding="utf-8").read()
    arrays = [(m.group(1), m.group(2)) for m in ARRAY.finditer(text)
              if m.group(1).endswith("_VERT") or m.group(1).endswith("_FRAG")]
    jobs = {}
    with concurrent.futures.ThreadPoolExecutor(max_workers=max(2, (os.cpu_count() or 4) - 1)) as pool:
        for name, body in arrays:
            words = [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", body)]
            jobs[name] = pool.submit(compile_shader, name, words)
        results = {}
        for name, job in jobs.items():
            results[name] = job.result()
            print("  %s: %d bytes" % (name, len(results[name])), flush=True)

    def replace_array(m):
        name = m.group(1)
        if name not in results:
            return m.group(0)
        return c_bytes(name, results[name])

    text = ARRAY.sub(replace_array, text)
    text = text.replace("const uint32_t *vert, *frag;", "const uint8_t *vert, *frag; /* DXBC */")
    # the pass tables carry the byte sizes of the two stages
    text = re.sub(r"\{(\w+_VERT), (\w+_FRAG), \d+, \d+,", r"{\1, \2, sizeof(\1), sizeof(\2),", text)
    text = text.replace("Generated by tools/make-royale.py", "Generated by tools/make-d3d-chains.py from shaders_royale.h (tools/make-royale.py)")
    banner = "/* Direct3D 11 bytecode (fxc) of %s's shaders: generated by tools/make-d3d-chains.py, do not edit. */\n" % header
    text = banner + text
    open(os.path.join(out_dir, out_name), "w", encoding="utf-8", newline="\n").write(text)
    print("wrote %s" % out_name)


for header, out_name in HEADERS:
    print(header, flush=True)
    convert(header, out_name)
