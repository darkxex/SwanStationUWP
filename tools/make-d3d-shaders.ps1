<#
  SwanStationUWP - compiles the GPU interface's shaders (src\platform\uwp\ui.hlsl) with fxc and writes them as C arrays
  into src\platform\uwp\shaders_d3d.h (committed, so builds don't need a shader compiler). Run after changing them.
  SPDX-License-Identifier: GPL-3.0-or-later
#>
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$fxc = Get-ChildItem "${env:ProgramFiles(x86)}\Windows Kits\10\bin\*\x64\fxc.exe" | Sort-Object FullName | Select-Object -Last 1
if (-not $fxc) { throw "fxc.exe (Windows SDK) not found." }
$dir = Join-Path $root "src\platform\uwp"
$tmp = Join-Path $env:TEMP "ss-d3d-shaders"
New-Item -ItemType Directory -Force -Path $tmp | Out-Null
$text = "/* Generated by tools/make-d3d-shaders.ps1 from ui.hlsl: do not edit. */`r`n"
foreach ($s in @(@("vs_main", "vs_5_0", "g_ui_vs"), @("ps_main", "ps_5_0", "g_ui_ps"))) {
    $out = Join-Path $tmp "$($s[2]).cso"
    & $fxc.FullName /nologo /O3 /E $s[0] /T $s[1] /Fo $out (Join-Path $dir "ui.hlsl")
    if ($LASTEXITCODE -ne 0) { throw "fxc failed for $($s[0])." }
    $bytes = [System.IO.File]::ReadAllBytes($out)
    $text += "static const unsigned char $($s[2])[$($bytes.Length)] = {`r`n"
    for ($i = 0; $i -lt $bytes.Length; $i += 16) {
        $n = [Math]::Min(16, $bytes.Length - $i)
        $text += "    " + ((0..($n - 1) | ForEach-Object { "0x{0:x2}" -f $bytes[$i + $_] }) -join ", ") + ",`r`n"
    }
    $text += "};`r`n"
}
[System.IO.File]::WriteAllText((Join-Path $dir "shaders_d3d.h"), $text)
Write-Host "wrote src\platform\uwp\shaders_d3d.h"
